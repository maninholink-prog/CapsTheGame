import {expect,it} from 'vitest';
import {availableNodes,createMapRun,enterNode,resolveCaveiraMap,resolveEvent} from '../src/run/adventure.js';
import {finishBattle,runBattle} from '../src/run/run.js';
import {createProfile} from '../src/profile/profile.js';
import {settleBattle,startAccount} from '../src/profile/rewards.js';
import {decodeSave,encodeSave} from '../src/profile/storage.js';
import {sessionFromBattle} from '../src/ui/session.js';
import {renderRun} from '../src/ui/run-view.js';
import {difficultyRules} from '../src/run/difficulty.js';
import type {Difficulty} from '../src/run/difficulty.js';

it.each(Object.keys(difficultyRules) as Difficulty[])('keeps the %s route shape and makes the Megalodonte optional',difficulty=>{
 const run=createMapRun(42,'kylast',difficulty,'caveira-dourada');
 expect(run.map?.nodes).toHaveLength(difficultyRules[difficulty].nodes);
 const trial=run.map!.nodes.find(n=>n.event==='caveira-trial')!;
 const elite=run.map!.nodes.find(n=>run.encounters?.[n.id]==='caveira-megalodon')!;
 expect(run.map!.nodes.some(n=>n.next.includes(trial.id)&&n.next.includes(elite.id))).toBe(true);
 expect(run.map!.nodes.filter(n=>n.event?.startsWith('shop-'))).toHaveLength(2);
 expect(Object.values(run.encounters!)).not.toContain('caveira-captain');
});

it.each([false,true])('pays the main victory once and opens the secret with optional clue (%s)',hint=>{
 let run=createMapRun(42,'kylast','common','caveira-dourada');
 const profile=startAccount(createProfile('Teste','kylast',42,0),run,'caveira');
 expect(run.encounters?.start).toBe('caveira-crossing');
 const map=run.map!;
 const trial=map.nodes.find(n=>n.event==='caveira-trial')!;
 const fork=map.nodes.find(n=>n.next.includes(trial.id))!;
 map.current=fork.id;map.visited=[fork.id];
 expect(availableNodes(run).some(n=>run.encounters?.[n.id]==='caveira-megalodon')).toBe(true);
 run=resolveEvent(enterNode(run,trial.id),hint);
 const final=map.nodes.find(n=>n.kind==='finalboss')!;
 run.map!.current=map.nodes.find(n=>n.next.includes(final.id))!.id;
 run=enterNode(run,final.id);
 const battle=runBattle(run);
 expect(battle.encounter?.id).toBe('caveira-general');
 battle.phase='ended';battle.winner='p1';
 const won=finishBattle(run,battle);
 const paid=settleBattle(profile,run,won,battle,0);
 expect(won.stage).toBe('won');
 expect(paid.account?.settled).toBe(true);
 expect(paid.stones).toBe(150);
 expect(paid.boosters.common).toBe(1);
 expect(renderRun(won)).not.toContain('Investigar a enseada');
 const left=resolveCaveiraMap(won,'leave');
 expect(left.caveiraAftermath).toBeUndefined();
 expect(()=>resolveCaveiraMap(left,'inspect')).toThrow();
 const chart=resolveCaveiraMap(won,'inspect');
 expect(renderRun(chart)).toContain('Investigar a enseada');
 expect(renderRun(chart).includes('Quando o mar se cala')).toBe(hint);
 expect(decodeSave(encodeSave({profile:paid,run:chart,session:null})).run).toEqual(chart);
 expect(()=>resolveCaveiraMap(won,'fight')).toThrow();
 const secret=resolveCaveiraMap(chart,'fight');
 const captain=runBattle(secret);
 expect(captain.encounter?.id).toBe('caveira-captain');
 const session=sessionFromBattle(captain,secret.battleSeed);
 expect(decodeSave(encodeSave({profile:paid,run:secret,session})).run).toEqual(secret);
 captain.phase='ended';captain.winner=hint?'p1':'p2';
 const done=finishBattle(secret,captain);
 expect(done.stage).toBe('won');
 expect(done.caveiraAftermath).toBe(hint?'won':'lost');
 expect(settleBattle(paid,secret,done,captain,0)).toEqual(paid);
 expect(()=>resolveCaveiraMap(done,'fight')).toThrow();
});
